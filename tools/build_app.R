#!/usr/bin/env Rscript
# Copy the package R code into the app so the Shinylive (webR) build runs the
# same functions as the installed package. Run from the package root:
#   Rscript tools/build_app.R
files <- sort(list.files("R", pattern = "\\.R$", full.names = TRUE))
files <- setdiff(files, "R/powerscope-package.R")
hdr <- c("# GENERATED by tools/build_app.R from the package R/ directory. Do not edit.",
         sprintf("# powerscope %s", read.dcf("DESCRIPTION", "Version")[1, 1]), "")
body <- unlist(lapply(files, function(f) c(sprintf("# ---- %s ----", f), readLines(f), "")))
writeLines(c(hdr, body), "app/powerscope_core.R")
cat("wrote app/powerscope_core.R from", length(files), "files\n")
